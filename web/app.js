function readPreference(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}

function savePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Preferences remain active for this page view. */ }
}

let language = readPreference("tbaf-language", "en") === "es" ? "es" : "en";
const systemTheme = window.matchMedia?.("(prefers-color-scheme: light)").matches ? "light" : "dark";
let theme = readPreference("tbaf-theme", systemTheme) === "light" ? "light" : "dark";
