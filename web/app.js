elements.theme.addEventListener("change", () => {
  theme = elements.theme.value === "light" ? "light" : "dark";
  savePreference("tbaf-theme", theme);
  applyPreferences();
});

function node(tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined && text !== null) element.textContent = String(text);
  return element;
}

function setStatus(message, kind = "info") {
  elements.status.textContent = message;
  elements.status.dataset.kind = kind;
}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function validatePackage(value) {
  if (!isObject(value) || !["tbaf.review-package/v2", "tbaf.review-package/v3"].includes(value.schema_version)) {
    throw new Error(t("unsupportedPackage"));
  }
  if (!isObject(value.change) || !SHA_PATTERN.test(value.change.head_sha || "")
      || !Array.isArray(value.change.paths) || !isObject(value.attention)
      || !Array.isArray(value.attention.tasks) || !Array.isArray(value.claims)
      || !Array.isArray(value.checks) || !Array.isArray(value.observations)
      || !isObject(value.policy) || !SHA_PATTERN.test(value.sha256 || "")) {
    throw new Error(t("missingFields"));
  }
  const collections = [value.change.paths, value.attention.tasks, value.claims, value.checks, value.observations];
  if (collections.some((rows) => rows.length > MAX_ROWS_PER_SECTION)) {
    throw new Error(t("tooManyRows", { limit: MAX_ROWS_PER_SECTION }));
  }
  if (value.change.paths.some((path) => typeof path !== "string" || path.length > MAX_PATH_CHARS)) {
    throw new Error(t("invalidPath"));
  }
  if (value.sast_evidence !== undefined) {
    const sast = value.sast_evidence;
    if (!isObject(sast) || sast.schema_version !== "tbaf.sast-evidence/v1"
        || !["available", "no_findings", "partial", "unavailable"].includes(sast.status)
        || !Array.isArray(sast.findings) || sast.findings.length > MAX_ROWS_PER_SECTION
        || !Number.isInteger(sast.reported_finding_count) || sast.reported_finding_count < 0
        || !Number.isInteger(sast.unchanged_path_finding_count) || sast.unchanged_path_finding_count < 0
        || !Number.isInteger(sast.omitted_finding_count) || sast.omitted_finding_count < 0
        || (sast.status === "unavailable" ? sast.source !== null || sast.scanner !== null
          : !isObject(sast.source) || sast.source.head_sha !== value.change.head_sha
            || sast.source.ref !== `refs/merge-requests/${value.change.mr_iid}/head`
            || sast.source.binding !== "gitlab_pipeline_and_job_metadata"
            || !Number.isInteger(sast.source.pipeline_id) || !Number.isInteger(sast.source.job_id)
            || !isObject(sast.scanner) || typeof sast.scanner.name !== "string"
            || typeof sast.scanner.version !== "string" || typeof sast.scanner.analyzer !== "string"
            || typeof sast.scanner.analyzer_version !== "string")
        || sast.findings.some((finding) => !isObject(finding) || typeof finding.name !== "string"
          || !["Info", "Unknown", "Low", "Medium", "High", "Critical"].includes(finding.severity) || typeof finding.path !== "string"
          || !value.change.paths.includes(finding.path) || !Number.isInteger(finding.start_line)
          || !Number.isInteger(finding.end_line) || finding.start_line < 1 || finding.end_line < finding.start_line
          || !Array.isArray(finding.identifiers) || finding.identifiers.length > 20
          || finding.identifiers.some((identifier) => !isObject(identifier)
            || typeof identifier.type !== "string" || identifier.type.length > 64
            || typeof identifier.value !== "string" || identifier.value.length > 256))) {
      throw new Error(t("invalidSast"));
    }
  }
  if (value.schema_version === "tbaf.review-package/v3" && value.sast_evidence === undefined) {
    throw new Error(t("invalidSast"));
  }
  return value;
}

function humanize(value) {
  return String(value || "unknown").replaceAll("_", " ").toLowerCase();
}

function minutes(value) {
  return Number.isInteger(value) ? `${value} ${t("minutes")}` : t("unknownValue");
}

function renderList(target, rows, emptyText, renderRow) {
  target.replaceChildren();
  if (!rows.length) {
    target.append(node("p", "empty-list", emptyText));
    return;
  }
  for (const row of rows) target.append(renderRow(row));
}

function validateLinkedEnvelope(value) {
  if (!isObject(value) || value.schema_version !== "tbaf.review-package-link/v2"
      || !isObject(value.change_mapper) || !isObject(value.review_package)) {
    throw new Error(t("unsupportedLinked"));
  }
  const mapper = value.change_mapper;
  const coverage = mapper.diff_coverage;
  if (mapper.epistemic_status !== "CANDIDATE" || !Array.isArray(mapper.observations)
      || mapper.observations.length > MAX_ROWS_PER_SECTION || !isObject(coverage)
      || !["complete", "partial", "unknown"].includes(coverage.status)
      || !Array.isArray(coverage.paths) || coverage.paths.length > 2000
      || coverage.paths.some((path) => typeof path !== "string" || path.length > MAX_PATH_CHARS)
      || !Array.isArray(coverage.limitations) || coverage.limitations.length > 100
      || coverage.limitations.some((item) => typeof item !== "string" || item.length > 1000)
      || mapper.observations.some((item) => !isObject(item)
        || typeof item.text !== "string" || item.text.length > 20_000)) {
    throw new Error(t("invalidMapper"));
  }
  return { packageData: validatePackage(value.review_package), mapper };
}

function renderMapper(mapper) {
  elements.mapperSection.hidden = !mapper;
  elements.mapperNav.hidden = !mapper;
  if (!mapper) return;

  const coverage = mapper.diff_coverage;
  const pill = document.querySelector("#mapper-coverage");
  pill.textContent = coverage.assertion_source === "reported_by_agent_not_independently_verified"
    ? `${t("reported")} ${label(coverage.status)}`
    : t("unknownLegacy");
  pill.className = `state-pill coverage-${coverage.status}`;
  document.querySelector("#mapper-assurance").textContent =
    coverage.assertion_source === "reported_by_agent_not_independently_verified"
      ? t("mapperAssuranceReported")
      : t("mapperAssuranceLegacy");

  const limitations = document.querySelector("#mapper-limitations");
  limitations.replaceChildren();
  const rows = [
    ...coverage.limitations.map((item) => `${t("limitation")}: ${item}`),
    ...coverage.paths.map((path) => `${t("affectedPath")}: ${path}`),
  ];
  if (!rows.length) rows.push(t("noCoverageLimits"));
  for (const row of rows) limitations.append(node("p", "item-meta coverage-detail", row));

  renderList(document.querySelector("#mapper-observations"), mapper.observations,
    t("noMapperObservations"), (observation) => {
      const card = node("section", "item-card");
      const top = node("div", "item-topline");
      top.append(node("h3", "item-title", observation.id || "Candidate"));
      top.append(node("span", "candidate-pill", t("candidate")));
      card.append(top, node("p", "item-text", observation.text || "No observation text supplied."));
      const locations = Array.isArray(observation.locations) ? observation.locations : [];
      if (locations.length) {
        card.append(node("p", "item-meta", locations.map((location) =>
          `${location.path}:${location.start_line}-${location.end_line}`).join(" · ")));
      }
      return card;
    });
}

function renderSast(packageData) {
  const sast = packageData.sast_evidence;
  const status = document.querySelector("#sast-status");
  const assurance = document.querySelector("#sast-assurance");
  const source = document.querySelector("#sast-source");
  const list = document.querySelector("#sast-findings");
  const state = sast?.status || "legacy";
  status.textContent = label(state);
  status.className = `state-pill sast-${state}`;
  assurance.textContent = !sast ? t("sastLegacy")
    : state === "unavailable" ? `${t("sastUnavailable")} ${t("sastReason")}: ${label(sast.reason_code)}`
      : state === "no_findings" ? t("sastNoFindings")
        : state === "partial" ? `${t("sastFindingsSummary", { count: sast.findings.length })} ${t("sastPartial")}`
          : t("sastFindingsSummary", { count: sast.findings.length });
  source.textContent = sast?.source
    ? t("sastReportSource", {
      scanner: sast.scanner.name, version: sast.scanner.version,
      analyzer: sast.scanner.analyzer, analyzerVersion: sast.scanner.analyzer_version,
      pipeline: sast.source.pipeline_id, job: sast.source.job_id, sha: sast.source.head_sha,
    })
    : "";
  list.replaceChildren();
  if (sast?.unchanged_path_finding_count) {
    list.append(node("p", "item-meta", `${t("sastOutsideDiff")}: ${sast.unchanged_path_finding_count}`));
  }
  if (sast?.omitted_finding_count) {
    list.append(node("p", "item-meta", t("sastOmitted", { count: sast.omitted_finding_count })));
  }
  for (const finding of sast?.findings || []) {
    const card = node("section", "item-card sast-finding");
    const top = node("div", "item-topline");
    top.append(node("h3", "item-title", finding.name));
    top.append(node("span", `severity-pill severity-${String(finding.severity).toLowerCase()}`, label(finding.severity)));
    card.append(top, node("p", "item-meta", `${finding.path}:${finding.start_line}-${finding.end_line}`));
    if (finding.identifiers.length) {
      card.append(node("p", "item-meta", `${t("sastIdentifiers")}: ${finding.identifiers.map((item) => `${item.type}:${item.value}`).join(" · ")}`));
    }
    list.append(card);
  }
}

function renderPackage(packageData, isExample, mapper = null) {
  const change = packageData.change;
  const attention = packageData.attention;
  const route = attention.route;

  document.querySelector("#change-title").textContent = `${language === "es" ? "Solicitud de cambio" : "Merge request"} !${change.mr_iid}`;
  document.querySelector("#change-project").textContent = change.project;
  document.querySelector("#change-iid").textContent = `!${change.mr_iid}`;
  document.querySelector("#change-sha").textContent = change.head_sha;
  document.querySelector("#change-path-count").textContent = String(change.paths.length);
  document.querySelector("#policy-name").textContent = `${packageData.policy.id} · v${packageData.policy.version}`;

  const paths = document.querySelector("#changed-paths");
  paths.replaceChildren();
  for (const path of change.paths) paths.append(node("li", "path-item", path));

  const routeTitle = document.querySelector("#route-title");
  routeTitle.textContent = label(route);
  routeTitle.className = `route-title route-${String(route).toLowerCase()}`;
  document.querySelector("#route-glyph").textContent = route === "COVERED_BY_EVIDENCE" ? "✓" : "!";
  document.querySelector("#route-description").textContent = {
    COVERED_BY_EVIDENCE: t("routeCovered"),
    TARGETED_REVIEW: t("routeTargeted"),
    DEEP_REVIEW: t("routeDeep"),
  }[route] || t("unknownRoute");

  renderList(document.querySelector("#route-reasons"), attention.reasons || [], t("noRouteReasons"),
    (reason) => node("li", "reason-item", label(reason)));
  document.querySelector("#capacity-value").textContent = minutes(attention.capacity_minutes);
  document.querySelector("#demand-value").textContent = minutes(attention.known_demand_minutes);
  document.querySelector("#uncovered-value").textContent = minutes(attention.uncovered_known_minutes);
  document.querySelector("#schedule-state").textContent = `${t("scheduleState")}: ${label(attention.schedule_state)}`;

  const policyClaims = Array.isArray(packageData.policy.claims) ? packageData.policy.claims : [];
  const statements = new Map(policyClaims.filter((claim) => isObject(claim) && typeof claim.statement === "string")
    .map((claim) => [claim.id, claim.statement]));
  document.querySelector("#claim-count").textContent = String(packageData.claims.length);
  renderList(document.querySelector("#claims-list"), packageData.claims, t("noClaims"), (claim) => {
    const card = node("section", "item-card");
    const top = node("div", "item-topline");
    top.append(node("h3", "item-title", claim.claim_id));
    top.append(node("span", `state-pill state-${humanize(claim.evidence_state).replaceAll(" ", "-")}`, label(claim.evidence_state)));
    card.append(top, node("p", "item-text", claim.statement || statements.get(claim.claim_id) || t("noClaimStatement")));
    const reasons = Array.isArray(claim.reasons) ? claim.reasons : [];
    if (reasons.length) card.append(node("p", "item-meta", `${t("openReasons")}: ${reasons.map(label).join(" · ")}`));
    return card;
  });

  document.querySelector("#check-count").textContent = String(packageData.checks.length);
  renderList(document.querySelector("#checks-list"), packageData.checks, t("noChecks"), (check) => {
    const card = node("section", "item-card");
    const top = node("div", "item-topline");
    top.append(node("h3", "item-title", check.id));
    top.append(node("span", `state-pill state-${humanize(check.status).replaceAll(" ", "-")}`, label(check.status)));
    card.append(top, node("p", "item-meta", `${check.source?.name || t("unknown")} ${check.source?.version || ""} · ${check.scope || t("unknown")}`));
    if (check.details) card.append(node("p", "item-text", check.details));
    return card;
  });

  renderSast(packageData);

  document.querySelector("#task-count").textContent = String(attention.tasks.length);
  renderList(document.querySelector("#tasks-list"), attention.tasks, t("noTasks"), (task) => {
    const card = node("section", "item-card task-item");
    const top = node("div", "item-topline");
    top.append(node("h3", "item-title", task.claim_id || task.task_id));
    top.append(node("span", "task-minutes", minutes(task.required_minutes)));
    card.append(top, node("p", "item-meta", `${label(task.route)} · ${t("taskConsequence", { value: label(task.consequence) })}`));
    const reasons = Array.isArray(task.reason_codes) ? task.reason_codes : [];
    if (reasons.length) card.append(node("p", "item-text", reasons.map(label).join(" · ")));
    return card;
  });

  document.querySelector("#observation-count").textContent = String(packageData.observations.length);
  renderList(document.querySelector("#observations-list"), packageData.observations, t("noObservations"), (observation) => {
    const card = node("section", "item-card");
    const top = node("div", "item-topline");
    top.append(node("h3", "item-title", observation.id));
    top.append(node("span", "candidate-pill", t("candidate")));
    card.append(top, node("p", "item-text", observation.text));
    card.append(node("p", "item-meta", `${observation.source?.agent || t("unknown")} ${observation.source?.version || ""} · ${label(observation.kind)} · ${label(observation.impact)}`));
    if (Array.isArray(observation.locations) && observation.locations.length) {
      card.append(node("p", "item-meta", observation.locations.map((location) => `${location.path}:${location.start_line}-${location.end_line}`).join(" · ")));
    }
    return card;
  });

  document.querySelector("#package-digest").textContent = packageData.sha256;
  renderMapper(mapper);
  elements.exampleNotice.hidden = !isExample;
  elements.empty.hidden = true;
  elements.view.hidden = false;
  setStatus(isExample ? t("exampleLoaded") : t("localLoaded"), "success");
  currentPackage = { packageData, mapper, isExample };
}

async function loadText(text, isExample = false) {
  if (new Blob([text]).size > MAX_PACKAGE_BYTES) throw new Error(t("packageTooLarge"));
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new Error(t("invalidJson"));
  }
  const documentData = parsed?.schema_version === "tbaf.review-package-link/v2"
    ? validateLinkedEnvelope(parsed)
    : { packageData: validatePackage(parsed), mapper: null };
  renderPackage(documentData.packageData, isExample, documentData.mapper);
}

elements.file.addEventListener("change", async () => {
  const file = elements.file.files?.[0];
  if (!file) return;
  setStatus(t("readingFile"));
  try {
    if (file.size > MAX_PACKAGE_BYTES) throw new Error(t("fileTooLarge"));
    await loadText(await file.text());
  } catch (error) {
    const previousPackageVisible = !elements.view.hidden;
    setStatus(`${error.message || t("invalidJson")}${previousPackageVisible ? t("previousKept") : ""}`, "error");
  }
});

elements.demo.addEventListener("click", async () => {
  setStatus(t("loadingExample"));
  elements.demo.disabled = true;
  try {
    const response = await fetch("/demo-review-package.json", { cache: "no-store" });
    if (!response.ok) throw new Error(t("exampleFailed", { status: response.status }));
    await loadText(await response.text(), true);
  } catch (error) {
    const previousPackageVisible = !elements.view.hidden;
    setStatus(`${error.message || t("invalidJson")}${previousPackageVisible ? t("previousKept") : ""}`, "error");
  } finally {
    elements.demo.disabled = false;
  }
});

